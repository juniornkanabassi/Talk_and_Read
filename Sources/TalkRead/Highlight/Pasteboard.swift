// Serialised pasteboard transactions (PLAN decision 6, Sol TR-001): each one snapshots every item and every type's
// data, runs its body, and restores the snapshot before the next transaction may start, so a capture copy and a
// dictation paste can never restore each other's temporary text.
import AppKit

actor PasteboardGate {
    static let shared = PasteboardGate()
    /// `eventSourceUserData` on every key event we post (⌘V), so our own event tap can ignore it ("TRDR").
    static let eventTag: Int64 = 0x5452_4452

    nonisolated(unsafe) let pasteboard: NSPasteboard
    /// changeCount of the last change this transaction made (a write) or caused (a copy it waited for).
    @MainActor private var ours: Int?
    /// What the running transaction puts back; nil when idle or once restored.
    @MainActor private var snapshot: Snapshot?
    /// Set by `shutdown`: from then on nothing may change the pasteboard.
    @MainActor private var closed = false
    private var busy = false
    private var waiters: [CheckedContinuation<Void, Never>] = []
    private var idleWaiters: [CheckedContinuation<Void, Never>] = []

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    /// A cancelled task still runs its body (the body checks `Task.isCancelled` before acting) and still gets the
    /// clipboard back: the restore runs on every exit, return, throw or cancellation; only the process ending skips it,
    /// which is why quitting goes through `shutdown(grace:)`.
    func transaction<T>(_ body: @MainActor () async throws -> T) async rethrows -> T {
        if busy { await withCheckedContinuation { waiters.append($0) } } else { busy = true }
        defer { handOver() }
        await begin()
        do {
            let result = try await body()
            await restore()
            return result
        } catch {
            await restore()
            throw error
        }
    }

    /// Returns once no transaction is running or queued (immediately when idle).
    func waitUntilIdle() async {
        guard busy else { return }
        await withCheckedContinuation { idleWaiters.append($0) }
    }

    /// Quitting (Sol #20). Closes the gate: every later `write` and `prepareToChange`, in queued and new transactions
    /// too, is refused (returns nil), so those bodies run but change nothing. Returns once no transaction is running or
    /// queued, or after `grace` seconds; either way the running transaction's snapshot is put back first if its
    /// temporary text is still on the pasteboard (a hung body), so quitting never leaves the user's clipboard replaced.
    func shutdown(grace: Double) async {
        await close()
        let deadline = Date().addingTimeInterval(grace)
        while busy, Date() < deadline, !Task.isCancelled { try? await Task.sleep(for: .milliseconds(20)) }
        await restore()
    }

    /// FIFO: the next queued transaction starts only after this one restored; with none queued the gate is idle.
    private func handOver() {
        if !waiters.isEmpty { return waiters.removeFirst().resume() }
        busy = false
        idleWaiters.forEach { $0.resume() }
        idleWaiters = []
    }

    /// Call right before this transaction changes the pasteboard or asks an app to (Edit ▸ Copy). If someone else
    /// changed it since the snapshot (Junior copied meanwhile), it snapshots again, so the restore brings back that
    /// newer copy instead of losing it (Sol #21). Returns the changeCount the change will move off; nil when the gate
    /// is closed for quitting, and then the caller must change nothing (no write, no Copy, no paste).
    // ponytail: the check and the change are microseconds apart, not atomic; NSPasteboard has no compare-and-swap.
    @MainActor func prepareToChange() -> Int? {
        guard !closed else { return nil }
        let now = pasteboard.changeCount
        if now != snapshot?.changeCount, now != ours { begin() }
        return now
    }

    /// Writes `string` as the only item, marked transient, concealed and auto-generated so clipboard managers skip it.
    /// Returns the new changeCount, or nil when refused because the app is quitting (`shutdown`): the pasteboard is
    /// untouched and the caller must not paste. Call only inside a transaction.
    @MainActor @discardableResult func write(_ string: String) -> Int? {
        guard prepareToChange() != nil else { return nil }
        let item = NSPasteboardItem()
        item.setString(string, forType: .string)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
        }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        ours = pasteboard.changeCount
        return pasteboard.changeCount
    }

    /// Polls every 10 ms until changeCount moves off `count` and takes that first observed change as ours (we asked the
    /// app to copy). It must still be the current one 20 ms later: any later change is someone else's (Junior copying
    /// meanwhile), so the copy is not verified (false) and the restore leaves that newer clipboard alone (Sol #3).
    /// False too on timeout. Cancellation does not cut the wait short: once Copy is pressed, the app's answer has to
    /// land inside the transaction (Sol #22).
    // ponytail: a second copy landing inside the same 10 ms poll as the app's is indistinguishable from it.
    @MainActor func waitForChange(from count: Int, timeout: Double) async -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while pasteboard.changeCount == count {
            if Date() >= deadline { return false }
            await pause(0.01)
        }
        let first = pasteboard.changeCount
        ours = first
        await pause(0.02)   // settle: an app writing in two steps, or a newer copy
        return pasteboard.changeCount == first
    }

    /// The pasteboard's string, only while it still holds this transaction's own change (checked again after the read,
    /// so a copy by someone else in between is never returned as ours).
    @MainActor func ownString() -> String? {
        guard let ours, pasteboard.changeCount == ours, let string = pasteboard.string(forType: .string),
              pasteboard.changeCount == ours else { return nil }
        return string
    }

    /// Not `Task.sleep`, which a cancelled task skips.
    @MainActor private func pause(_ seconds: Double) async {
        await withCheckedContinuation { done in DispatchQueue.main.asyncAfter(deadline: .now() + seconds) { done.resume() } }
    }

    @MainActor private func close() { closed = true }

    // MARK: - Snapshot

    private struct Snapshot: Sendable {
        let items: [[(type: String, data: Data)]]
        let changeCount: Int
    }

    @MainActor private func begin() {
        ours = nil
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type.rawValue, $0) } }
        }
        snapshot = Snapshot(items: items, changeCount: pasteboard.changeCount)
    }

    /// Puts the snapshot back only if the pasteboard still holds what this transaction put there; a change by anyone
    /// else (the user copied meanwhile) is left alone. Once per snapshot: a later call (the hung body `shutdown`
    /// already restored for) does nothing.
    @MainActor private func restore() {
        defer { snapshot = nil; ours = nil }
        let now = pasteboard.changeCount
        guard let snapshot, now != snapshot.changeCount, now == ours else { return }
        pasteboard.clearContents()
        let items = snapshot.items.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }
}
